function kind(tn) {
	if (/סטנד/.test(tn)) return 'stand';
	if (/טבעת/.test(tn)) return 'ring';
	if (/עגיל/.test(tn)) return 'earring';
	if (/צמיד/.test(tn)) return 'bracelet';
	if (/שרשרת|צ׳וקר/.test(tn)) return 'necklace';
	if (/תליון/.test(tn)) return 'pendant';
	return 'other';
}

function build(id, s, i) {
	const [kw, tn, feat, mat, flags = '', extra] = s;
	const t = tn + ' | ALMORA';
	// meta description: starts with the keyphrase, 120-155 characters
	const base = feat.startsWith(kw) ? feat : kw + ': ' + feat;
	const fit = CTA.map((x) => (base + '. ' + x + ' ALMORA.').replace(/\.\./g, '.')).filter((x) => x.length >= 120 && x.length <= 155);
	const d = fit.length ? fit[i % fit.length] : (base + '. ' + CTA[3] + ' ALMORA.').replace(/\.\./g, '.');
	const out = { t, d, k: kw };

	if (/Y/.test(flags) || NO_LONG.has(id) || !LONG.has(id)) return out;

	const li = [];
	if (mat === 'a') li.push('חומר: כסף 925, סגסוגת שמכילה 92.5% כסף');
	else if (mat === 's') li.push('חומר: כסף');
	else if (mat === 'b') li.push('חומר: בראס');
	if (/z/.test(flags)) li.push('אבנים: אבני זרקון (זירקוניה מעוקבת), אבן סינתטית');
	if (/M/.test(flags)) li.push('אבן: מוסונייט (סיליקון קרביד), אבן שמיוצרת במעבדה');
	if (/o/.test(flags)) li.push('אבן: אוניקס שחור');
	if (extra) li.push(extra);
	const wear = {
		ring: 'אפשר לענוד אותה לבד או לשלב עם טבעות נוספות.',
		earring: 'אפשר לענוד אותם לבד או לשלב עם עגילים נוספים באוזן.',
		bracelet: 'אפשר לענוד אותו לבד או לשלב עם צמידים נוספים.',
		necklace: 'אפשר לענוד אותה לבד או לשלב עם שרשראות נוספות.',
		pendant: 'אפשר לענוד אותו לבד או לשלב עם שרשראות נוספות.',
		other: 'אפשר לענוד אותו לבד או לשלב עם תכשיטים נוספים.',
		stand: '',
	}[kind(tn)];
	let html = '<p>' + kw + ': ' + feat + '.</p>';
	if (li.length) html += '<h3>פרטי התכשיט</h3><ul>' + li.map((x) => '<li>' + x + '</li>').join('') + '</ul>';
	html += '{{OPTIONS}}';
	if (wear) html += '<p>' + wear + '</p>';
	html += '<h3>טיפול בתכשיט</h3><p>מומלץ להסיר את התכשיט לפני מקלחת, שחייה, פעילות גופנית וניקיון הבית, לנגב בבד רך ולאחסן בנפרד, בשקית או בקופסה.</p>';
	html += SHIP;
	out.long = html;
	out.short = feat + '.';
	return out;
}

